package ias

import "bytes"

// Family is the CIE chip supplier family, which decides how the IAS application is selected and how the DH domain
// parameters are read.
type Family int

const (
	FamilyUnknown Family = iota
	FamilyGemalto
	FamilySTM
	FamilyNXP
	FamilyActalis
	FamilyBit4id
)

func (f Family) String() string {
	switch f {
	case FamilyGemalto:
		return "Gemalto"
	case FamilySTM:
		return "STM"
	case FamilyNXP:
		return "NXP"
	case FamilyActalis:
		return "Actalis"
	case FamilyBit4id:
		return "Bit4id"
	}
	return "unknown"
}

// selectsMF reports whether the family reaches IAS by selecting the MF (NXP and later) instead of the IAS AID.
func (f Family) selectsMF() bool { return f >= FamilyNXP }

