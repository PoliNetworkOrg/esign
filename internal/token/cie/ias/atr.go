// itj4 is the historical-bytes prefix shared by the Actalis and Bit4id applets ("IT J4"); the next byte is the batch.
var itj4 = []byte{0x80, 0x31, 0x80, 0x65, 0x49, 0x54, 0x4A, 0x34}

// Identify classifies an ATR. The reference sorts the bytes and tests set inclusion, which can match unrelated
// cards; this matches each pattern as a contiguous run, as OpenCIE does, and treats unlisted "ITJ4" batches as
// Actalis like OpenCIE.
func Identify(atr []byte) (Family, string) {
	for _, e := range atrTable {
		if bytes.Contains(atr, e.pattern) {
			return e.family, e.name
		}
	}
	if bytes.Contains(atr, itj4) {
		return FamilyActalis, "ITJ4"
	}
	return FamilyUnknown, ""
}
